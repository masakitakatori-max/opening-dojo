/** Notes for a book line: the deepest family in `lines` (SAN strings, deepest last) that has notes. */
export function notesFor(lines: string[]): { line: string; notes: OpeningNotes } | undefined {
  for (let i = lines.length - 1; i >= 0; i--) {
    const n = OPENING_NOTES.find((x) => x.lines.includes(lines[i]));
    if (n) return { line: lines[i], notes: n };
  }
  return undefined;
}
