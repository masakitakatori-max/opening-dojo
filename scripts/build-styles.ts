// Measure each GM's style from the ghost data (public/ghosts/*.json) with the same code the app
// uses for the user's games, and write src/data/gmStyles.ts. Also runs a split-half check:
// does a GM's held-out half come out nearest to the same GM?
//   node scripts/build-styles.ts
import { readFileSync, writeFileSync } from "node:fs";
import { GHOST_PLAYERS } from "../src/lib/ghosts.ts";
import { aggregate, analyzeGame, axisScores, nearestGms, AXES, type GameStats, type GmStyles } from "../src/lib/style.ts";

const PER_GM = 600;
const halves: Record<string, [GameStats[], GameStats[]]> = {};
const full: GmStyles = {};
for (const { id } of GHOST_PLAYERS) {
  const pd = JSON.parse(readFileSync(`public/ghosts/${id}.json`, "utf8"));
  const step = Math.max(1, Math.floor(pd.games.length / PER_GM));
  const stats: GameStats[] = [];
  for (let i = 0; i < pd.games.length; i += step) {
    const [, , , , result, moves, color] = pd.games[i];
    const s = analyzeGame({ moves: moves.split(" "), color, result });
    if (s) stats.push(s);
  }
  halves[id] = [stats.filter((_, i) => i % 2 === 0), stats.filter((_, i) => i % 2 === 1)];
  full[id] = aggregate(stats).m;
  console.log(id.padEnd(11), `${stats.length} games`);
}

// split-half validation
const a: GmStyles = Object.fromEntries(Object.entries(halves).map(([id, [x]]) => [id, aggregate(x).m]));
let hit = 0, top3 = 0;
for (const [id, [, y]] of Object.entries(halves)) {
  const rank = nearestGms(aggregate(y).m, a).map((r) => r.id);
  if (rank[0] === id) hit++;
  if (rank.slice(0, 3).includes(id)) top3++;
  console.log("held-out", id.padEnd(11), "→", rank.slice(0, 3).join(", "));
}
const n = Object.keys(halves).length;
console.log(`split-half: nearest = same GM in ${hit}/${n}, within top 3 in ${top3}/${n}`);

console.log("\naxis scores (50 = GM average):", AXES.map((x) => x.ja).join(" / "));
for (const id of Object.keys(full)) console.log(id.padEnd(11), AXES.map((x) => Math.round(axisScores(full[id], full)[x.id])).join(" / "));

const round = (v: number) => +v.toPrecision(4);
const body = Object.entries(full).map(([id, m]) => `  ${id}: ${JSON.stringify(Object.fromEntries(Object.entries(m).map(([k, v]) => [k, round(v)])))},`).join("\n");
writeFileSync("src/data/gmStyles.ts", `// Generated by scripts/build-styles.ts — style metrics of each GM (same measures as src/lib/style.ts).\nimport type { GmStyles } from "../lib/style.ts";\n\nexport const GM_STYLES: GmStyles = {\n${body}\n};\n\nexport const SPLIT_HALF = { same: ${hit}, top3: ${top3}, of: ${n} };\n`);
